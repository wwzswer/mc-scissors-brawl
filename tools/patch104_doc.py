# -*- coding: utf-8 -*-
"""补丁 104：RULES.md 打火石与持续伤害说明更新"""
import pathlib, re

F = pathlib.Path(r'D:\Documents\deepseek-harness\default-workspace\mc-scissors-brawl\RULES.md')
t = F.read_text(encoding='utf-8')
n = 0

old = "| 铁 | 打火石 | 1 | 0 | — | 无需判定：点燃目标，**3 次 0.5 火焰**（目标持有护甲则 2 次）。**全部次数在本回合末统一结算**，期间入水可取消 |"
new = "| 铁 | 打火石 | 1 | 0 | — | 无需判定：点燃目标，**接下来 3 个回合每回合结束各结算 1 次 0.5 火焰**（合计 1.5；目标持有护甲则只持续 2 回合）。入水可扑灭 |"
if old in t:
    t = t.replace(old, new, 1); n += 1
    print('  ok 打火石表格行')
else:
    t2, k = re.subn(r'\| 铁 \| 打火石 \|[^\n]*\|', new, t)
    if k:
        t = t2; n += k; print(f'  ok 打火石表格行（宽松 {k} 处）')
    else:
        print('  ! 未找到打火石表格行')

old2 = """- **持续伤害（火焰）**：点燃当回合**不立即扣血**，全部次数在**本回合所有玩家行动结束后**统一结算（最少也会产生一次效果）。
  例：打火石点燃 3 次 → 回合末一次性结算 3 × 0.5 = 1.5。
  **入水会把剩余次数设为 0**（本回合不再受该火焰伤害），流血同理被水清除。"""
new2 = """- **持续伤害（火焰）**：点燃当回合**不立即扣血**，在**每回合所有玩家行动结束后**结算。
  - **打火石**：每回合结算 1 次 0.5，持续 **3 个回合**（合计 1.5）；目标持有护甲则只持续 **2 个回合**。
  - **火焰附加 / 引雷 / 烟花**等：属于「当回合结算完」，当回合一次性结算各自次数。
  - **入水可扑灭**：剩余回合数直接归零，之后不再受到该火焰伤害；流血同理被水清除。"""
if old2 in t:
    t = t.replace(old2, new2, 1); n += 1
    print('  ok 持续伤害段落')
else:
    print('  ! 未找到持续伤害段落')

F.write_text(t, encoding='utf-8')
print(f'RULES.md 共更新 {n} 处')
